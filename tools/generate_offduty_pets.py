#!/usr/bin/env python3
"""Package original LVGL pet renders as transparent RGB565A8 Flash images."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("renders", type=Path)
    args = parser.parse_args()
    lines = ['/* Generated by tools/generate_offduty_pets.py; original project artwork. */', '#include "lvgl.h"']
    seen = {}
    for resting in range(2):
        for mood in range(8):
            raw = (args.renders / f"pet-{resting}-{mood}.bgra").read_bytes()
            assert len(raw) == 73 * 92 * 4
            colors, alpha = bytearray(), bytearray()
            for offset in range(0, len(raw), 4):
                b, g, r, a = raw[offset:offset + 4]
                colors.extend((((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)).to_bytes(2, "little"))
                alpha.append(a)
            assert min(alpha) == 0 and max(alpha) == 255 and sum(a > 0 for a in alpha) > 3000
            data = bytes(colors + alpha)
            name = f"od_pet_{'rest_' if resting else ''}{mood}"
            if data not in seen:
                seen[data] = name + "_data"
                lines.append(f"static const uint8_t {seen[data]}[] = {{")
                for offset in range(0, len(data), 24):
                    lines.append("    " + ",".join(f"0x{b:02x}" for b in data[offset:offset + 24]) + ",")
                lines.append("};")
            lines.append(f"const lv_image_dsc_t {name} = {{ .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .w = 73, .h = 92, .stride = 146 }}, .data_size = {len(data)}, .data = {seen[data]} }};")
    (ROOT / "assets/images/offduty/od_pets.c").write_text("\n".join(lines) + "\n")
    print(f"Pet assets: 16 states, {len(seen)} unique images, {sum(map(len, seen))} Flash bytes")

if __name__ == "__main__":
    main()
