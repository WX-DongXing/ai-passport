#!/usr/bin/env python3
"""Freeze the reference LVGL stamp raster without changing its pixels."""
import argparse
from pathlib import Path

def main():
    parser=argparse.ArgumentParser();parser.add_argument('images',type=Path);args=parser.parse_args()
    out=Path(__file__).resolve().parents[1]/'assets/images/offduty/od_stamps.c'
    out.parent.mkdir(parents=True,exist_ok=True)
    chunks=['/* Generated by tools/generate_offduty_stamps.py from LVGL reference rendering. */','#include "lvgl.h"']
    for mood in range(8):
        data=(args.images/f'done-{mood}-0.ppm').read_bytes()
        header,pixels=data.split(b'\n255\n',1);assert header==b'P6\n240 320' and len(pixels)==240*320*3
        raw=[]
        for y in range(160,250):
            for x in range(123,223):
                r,g,b=pixels[(y*240+x)*3:(y*240+x)*3+3]
                value=((r*31+127)//255<<11)|((g*63+127)//255<<5)|((b*31+127)//255)
                raw.extend((value&255,value>>8))
        assert len(raw)==18000
        chunks.append(f'static const uint8_t pixels_{mood}[18000]={{')
        chunks.extend('    '+','.join(f'0x{n:02x}' for n in raw[i:i+24])+',' for i in range(0,len(raw),24))
        chunks.extend(['};','const lv_image_dsc_t od_stamp_%d={.header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565,.w=100,.h=90,.stride=200},.data_size=18000,.data=pixels_%d};' % (mood,mood)])
    out.write_text('\n'.join(chunks)+'\n')

if __name__=='__main__':main()
